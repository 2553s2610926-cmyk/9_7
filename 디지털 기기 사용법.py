# ------------------------------------
# 사이드바: 기기 선택
# ------------------------------------
with st.sidebar:
    st.header("🧭 학습 메뉴")
    st.write("먼저 사용할 기기를 선택하세요.")

    device_names = list(DEVICES.keys())
    selected_device = st.selectbox(
        "어떤 기기를 사용하시나요?",
        device_names,
    )

    st.divider()
    st.markdown("### 📌 이용 안내")
    st.write("1. 기기를 선택합니다.")
    st.write("2. 배울 기능을 선택합니다.")
    st.write("3. 순서대로 따라 합니다.")
    st.write("4. 완료한 단계에 체크합니다.")

    st.caption("메뉴 위치는 기기와 제조사에 따라 다를 수 있습니다.")

# ------------------------------------
# 검색 및 기능 선택
# ------------------------------------
device_info = DEVICES[selected_device]
guides = device_info["guides"]

st.subheader(selected_device)
st.write(device_info["description"])

search_text = st.text_input(
    "🔍 기능 검색",
    placeholder="예: 전화, 주문, 인쇄, 인터넷",
)

matching_guides = [
    name
    for name in guides
    if search_text.strip().casefold() in name.casefold()
]

if not matching_guides:
    st.warning(
        "해당 기능을 찾지 못했어요. "
        "다른 단어를 입력하거나 검색창을 비워 보세요."
    )
    st.stop()

selected_guide = st.selectbox(
    "배우고 싶은 기능을 선택하세요.",
    matching_guides,
)

guide = guides[selected_guide]

st.divider()

# ------------------------------------
# 단계별 사용법
# ------------------------------------
st.subheader(f"🪜 {selected_guide}")
st.write("아래 순서대로 한 단계씩 따라 해 보세요.")

completed = 0
total = len(guide["steps"])

for index, step in enumerate(guide["steps"], start=1):
    with st.container(border=True):
        checked = st.checkbox(
            f"{index}단계. {step}",
            key=f"{selected_device}_{selected_guide}_{index}",
        )
        if checked:
            completed += 1

progress = completed / total if total else 0

st.markdown("### 📊 나의 학습 진행률")
st.progress(progress)
st.write(f"**{completed} / {total}단계 완료**")

if completed == total:
    st.success("모든 단계를 완료했어요! 잘하셨습니다. 🎉")
elif completed > 0:
    st.info("잘하고 있어요. 남은 단계도 천천히 연습해 보세요.")

# ------------------------------------
# 기기별 주의사항
# ------------------------------------
st.divider()

with st.container(border=True):
    st.subheader("💡 알아두면 좋은 팁")
    st.write(guide["tip"])

